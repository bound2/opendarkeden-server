#ifndef __GUILDTYPES_H__
#define __GUILDTYPES_H__

#include "SystemTypes.h"

//////////////////////////////////////////////////////////////////////////////
// Guild ID
//////////////////////////////////////////////////////////////////////////////
typedef WORD GuildID_t;
const int szGuildID = sizeof(GuildID_t);


//////////////////////////////////////////////////////////////////////////////
// Kind of guild
//////////////////////////////////////////////////////////////////////////////
typedef BYTE GuildType_t;
const int szGuildType = sizeof(GuildType_t);


//////////////////////////////////////////////////////////////////////////////
// Guild state (waiting for registration, active, disbanded)
//////////////////////////////////////////////////////////////////////////////
typedef BYTE GuildState_t;
const int szGuildState = sizeof(GuildState_t);


//////////////////////////////////////////////////////////////////////////////
// Rank of a guild member (master, server master, ordinary)
//////////////////////////////////////////////////////////////////////////////
typedef BYTE GuildMemberRank_t;
const int szGuildMemberRank = sizeof(GuildMemberRank_t);


//////////////////////////////////////////////////////////////////////////////
// Race of the guild
//////////////////////////////////////////////////////////////////////////////
typedef BYTE GuildRace_t;
const int szGuildRace = sizeof(GuildRace_t);


//////////////////////////////////////////////////////////////////////////////
// Kind of a guild vote
//////////////////////////////////////////////////////////////////////////////
typedef BYTE GuildVoteType_t;
const int szGuildVoteType = sizeof(GuildVoteType_t);


//////////////////////////////////////////////////////////////////////////////
// ID of a guild vote
//////////////////////////////////////////////////////////////////////////////
typedef uint GuildVoteID_t;
const int szGuildVoteID = sizeof(GuildVoteID_t);


//////////////////////////////////////////////////////////////////////////////
// Maximum length of a guild name
//////////////////////////////////////////////////////////////////////////////
const int GUILD_NAME_MAX_LENGTH = 20;

//////////////////////////////////////////////////////////////////////////////
// Guild introduction maximum length. The length travels in one byte, and
// every packet that carries an introduction budgets at least this many
// characters in its factory max.
//////////////////////////////////////////////////////////////////////////////
const uint GUILD_INTRO_MAX_LENGTH = 255;

//////////////////////////////////////////////////////////////////////////////
// Maximum amount of guild tax
//////////////////////////////////////////////////////////////////////////////
const Gold_t GUILD_TAX_BALANCE_MAX = 2000000000; // 2 billion

#endif
